def parts_trustworthy(case):
    """Можно ли по устройству ЭТОГО дела судить, какая часть на каком скане.

    Четыре условия, и все четыре куплены ошибкой детектора в первый же прогон.
    Первая версия спрашивала только `order == forward` — и обвинила верно
    подписанный лист брачной записи. Дело, на котором она споткнулась, само
    объявляло `parts_reliable: false` и `headers_noisy: true`; детектор
    этих полей не читал.
      · `order == forward` — книги идут по возрастанию скана;
      · `parts_reliable` — распознаватель шапок сам себе верит;
      · не `headers_noisy` — шапки не рваные;
      · перечень книг МОНОТОНЕН по (год, часть). Порядок «прямой» считается
        по годам, и внутри года части могут идти 3, 1, 3, 1 — при таком
        перечне «последняя начавшаяся книга» не значит ничего.
    """
    books = sorted(case.get("books") or [], key=lambda b: b[0])
    keys = [(b[1], b[2]) for b in books]
    return bool(books) and case.get("order") == "forward" \
        and bool(case.get("parts_reliable")) and not case.get("headers_noisy") \
        and keys == sorted(keys)


def kind_from_structure(stem, cases):
    """(вид, надёжно_ли) по устройству дела — ДЕТЕКТОР, а не источник.

    `cases` — раздел `cases` из data/case_structure.yaml. Берётся последняя
    книга, начавшаяся не позже этого скана.

    🔴 Второе значение — можно ли верить (`parts_trustworthy`). Возвращаем
    вид и в ненадёжном случае, но помеченным: молча ошибающийся детектор
    хуже отсутствующего, а предупреждение, которое нельзя устранить, —
    это фон, а не сигнал.
    """
    m = _STEM_RE.match(str(stem or ""))
    if not m:
        return None, False
    case = cases.get(m.group(1)) or cases.get(int(m.group(1))) or {}
    books = [b for b in (case.get("books") or []) if b and b[0] <= int(m.group(2))]
    if not books:
        return None, False
    part = max(books, key=lambda b: b[0])[2]
    return PART_KIND.get(part), parts_trustworthy(case)


def structure_denies_part(stem, kind, year, cases):
    """Правда ли, что устройство дела зовёт эту часть ОТСУТСТВУЮЩЕЙ.

    🔴 Проверка идёт В ОБРАТНУЮ СТОРОНУ, и она важнее прямой. `missing_parts`
    — это то, чем оправдывают отрицание: «записи о браке в деле нет» ничего
    не стоит, если части второй за этот год в деле и не было. Но лист,
    прочитанный глазами, — наблюдение, а `missing_parts` — вывод из шапок.
    ⇒ Когда они спорят, прав лист, а вычисленная структура неполна — и это
    надо знать немедленно, потому что на ней стоят отрицания.
    """
    m = _STEM_RE.match(str(stem or ""))
    part = {v: k for k, v in PART_KIND.items()}.get(kind)
    if not m or not part or not year:
        return False
    case = cases.get(m.group(1)) or cases.get(int(m.group(1))) or {}
    miss = case.get("missing_parts") or {}
    return part in (miss.get(str(year)) or miss.get(int(year)) or [])


