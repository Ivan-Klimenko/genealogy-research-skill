def load_folios(data_dir):
    """{стем файла: запись реестра} из data/folios.yaml.

    Пустой словарь, если файла нет: проект может его ещё не завести.
    """
    f = pathlib.Path(data_dir) / "folios.yaml"
    if not f.is_file():
        return {}
    doc = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
    return doc.get("folios") or {}


def folio_people(folio):
    """[{id, as, record, as_written, hyp}] — кто назван НА ЭТОМ листе.

    ⭐ ДВА ПОЛЯ ПРО ОТОЖДЕСТВЛЕНИЕ, заведены 2026-08-10, и они про разное.

    `as_written` — КАК ЧЕЛОВЕК НАЗВАН НА САМОМ ЛИСТЕ, дословно. Заполняется,
    когда написание расходится с именем в графе. Это та же дисциплина, что
    у дословной копии против пересказа: рядом с нашим утверждением стоят слова
    документа, и читателю видно, что лист говорит иначе.

    `hyp` — НА ЧЁМ ДЕРЖИТСЯ ОТОЖДЕСТВЛЕНИЕ. 🔴 Лист называет имя, а что это ИМЕННО
    НАШ человек — говорим МЫ, и говорить это молча нельзя. Живой случай: восприемник
    записан «Романъ Васильевъ Новоселовъ», а в графе он «Роман Андреев Сундуков»
    — третье написание отчества у одного человека. Опора есть (hyp_095 подтверждена),
    но без ссылки на неё привязка выглядела бы как совпадение имени, то есть как
    ровно то, что запрещает правило 1.
    ⚠️ Поле обязательно там, где `as_written` расходится с именем узла; валидатор
    проверяет, что гипотеза существует и не отклонена.
    """
    out = []
    for item in (folio.get("people") or []):
        if not isinstance(item, dict) or not item.get("id"):
            continue
        role = str(item.get("as") or "mentioned")
        out.append({"id": item["id"],
                    "as": role if role in ROLES else "mentioned",
                    "record": item.get("record"),
                    "of": str(item.get("of") or "").strip() or None,
                    "disputed": str(item.get("disputed") or "").strip() or None,
                    "as_written": str(item.get("as_written") or "").strip() or None,
                    "hyp": str(item.get("hyp") or "").strip() or None})
    return out


def record_groups(folio):
    """{номер записи: [люди этой записи]} — запись, а не разворот.

    ⚠️ Разворот и запись — разные вещи (правило 15): на одном скане бывает
    пять рождений. Роль относится к ЗАПИСИ, и группировать надо по ней.
    Люди без номера собираются под ключом None — так выглядят надгробие,
    фотография и лист семейных записей, где записи нумеровать нечем.
    """
    groups = {}
    for item in folio_people(folio):
        groups.setdefault(item.get("record"), []).append(item)
    return groups


def claimed_kinship(items):
    """[(кто, кому, роль, оспорено_ли)] — родство, которое ЗАЯВЛЯЕТ эта запись.

    🔴 Это утверждение ДОКУМЕНТА, а не наше. Совпадать с графом оно не обязано,
    и самый дорогой случай — как раз несовпадение: писарь метрики поставил
    в графу родителей главу двора, то есть деда, и запись честно называет
    отцом не того. Пока такое расхождение живёт прозой, оно невидимо;
    поле `disputed` называет гипотезу, которая расхождение разобрала.

    Адресат берётся из `of`, а если субъект в записи один — из него.
    """
    subj = [i for i in items if i["as"] in ("subject", "deceased")]
    out = []
    for it in items:
        if it["as"] not in ("parent", "spouse"):
            continue
        target = it["of"] or (subj[0]["id"] if len(subj) == 1
                              and subj[0]["id"] != it["id"] else None)
        if target:
            out.append((it["id"], target, it["as"], it["disputed"]))
    return out


def joint_mention_status(ends, src_stems, named, folio=None):
    """Проверяемо ли «названы вместе» ПО ЛИСТУ, а не по находке.

    `ends` — множество id обеих сторон связи; `src_stems` — листы источника;
    `named` — {стем: {кто назван}} по разобранным листам; `folio` — лист,
    указанный руками, если он указан.

    Возвращает (состояние, лист):
      `no_scan`   — у источника нет ни одного снимка, проверить нечем;
      `confirmed` — лист называет обе стороны (в `лист` — какой именно);
      `ambiguous` — таких листов несколько: связь доказана, точность цитаты нет;
      `not_named` — снимки есть, но ни один лист обоих не называет.

    🔴 ЗАЧЕМ. Правило 1 требует, чтобы обе стороны были названы в ОДНОМ
    документе. Основание же указывает на `src`, а источник у нас — НАХОДКА,
    и она бывает на дюжину разворотов. То есть главное правило проверялось
    на объекте, который документом не является. Реестр листов знает, кто
    на каком развороте, — и делает правило проверяемым впервые.

    ⚠️ Поле `folio` у основания — УТОЧНЕНИЕ, а не обязанность: на живом
    проекте лист определяется однозначно у 152 оснований из 286, и хранить
    руками то, что и так вычисляется верно, значит заводить ржавчину
    (тот же вывод, что и с координатой в шифре). Руками — там, где листов
    несколько (19) или где надо показать, какой именно разворот имелся в виду.
    """
    if folio:
        ok = ends <= named.get(folio, set())
        return ("confirmed" if ok else "not_named"), folio
    if not src_stems:
        return "no_scan", None
    hits = [st for st in src_stems if ends <= named.get(st, set())]
    if len(hits) == 1:
        return "confirmed", hits[0]
    if hits:
        return "ambiguous", None
    return "not_named", None


def ambiguous_addressee(folio, items):
    """Нужен ли в этой записи `of` — то есть «чей».

    🔴 Ответ зависит от ВИДА записи, и в этом весь смысл поля `kind`.
    В записи о рождении субъект один, младенец, и родители — его; сказать
    «чей» нечего. В записи о браке субъектов ДВА, жених и невеста, а отец
    назван обычно один — и без указания, чей он, запись читается как
    утверждение о родстве, которого документ не делал.
    ⚠️ Живой случай: «отец невесты» на брачной записи выглядел ровно как
    «отец жениха» — прогон «лист называет родителем, а ребра нет» дал
    18 пар, из которых бо́льшая часть оказалась этим артефактом формуляра.
    """
    kin = [i for i in items if i["as"] in ("parent", "spouse")]
    subj = [i for i in items if i["as"] in ("subject", "deceased")]
    return bool(kin) and len(subj) > 1


