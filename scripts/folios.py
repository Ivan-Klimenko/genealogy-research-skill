def attach(graph, sources_doc, folios, have, project=None):
    """{person_id: [запись, ...]} — снимки человека, по убыванию близости к нему.

    Запись: {file, stem, role, record, srcs, basis}.

    🔴 ОСНОВАНИЕ ОДНО, И ЭТО ГЛАВНОЕ, ЧТО НАДО ЗНАТЬ ОБ ЭТОЙ ФУНКЦИИ.
    `basis: 'folio'` — РЕЕСТР ЛИСТОВ НАЗЫВАЕТ ЧЕЛОВЕКА НА ЭТОМ ЛИСТЕ. Это
    наблюдение, сделанное глазами по снимку. Ничего другого снимок к карточке
    не привязывает: ни имя, ни отчество, ни архивный шифр (правило 1
    («совместное упоминание»)). Лист, у которого `people` не заполнен,
    не показывается НИКОМУ — и это честнее, чем догадка.

    ⚙️ ЗДЕСЬ БЫЛО ВТОРОЕ ОСНОВАНИЕ, `basis: 'source'`, И ОНО УДАЛЕНО 2026-08-11.
    Читалось так: пока лист не разобран по людям, снимок берётся через источник —
    но только если источник разбирает РОВНО ОДИН лист. Основание было переходным
    с самого начала и своё отработало: пока реестр наполнялся, оно держало снимки
    на карточках. К моменту удаления оно давало НОЛЬ привязок из 426 — реестр
    покрыл всё, — так что удаление ничего не изменило в выводе, и это и было
    условием: переходное снимают, когда оно перестало работать, а не когда
    надоело. На поведение стоит регрессионный тест (`tests/run_tests.py`,
    раздел «реестр листов»).

    ⚠️ А ВОТ `ref_folios` ОСТАВЛЕН, ВОПРЕКИ ПЕРВОНАЧАЛЬНОМУ ПЛАНУ, и причину
    надо назвать. План звал удалить парсер координат вместе с переходным
    основанием — но за время работы у парсера появилась вторая работа, к привязке
    отношения не имеющая: он говорит, КАКИЕ ИСТОЧНИКИ РАЗБИРАЮТ ЭТОТ ЛИСТ
    (поле `srcs` записи и подсказки в `caption_worklist.py`).
    Измерено на живом проекте, и цифры именно эти — первая прикидка их завышала.
    Источник у листа виден тремя путями: координата в шифре, путь `data/scans/…`,
    выписанный в дословной копии, и явное поле `folio.sources`. Третье заполнено
    у ОДНОГО листа из 189; второе покрывает 127 листов; а 52 листа видны ТОЛЬКО
    через шифр, и на них приходится 135 привязок из 427. ⇒ Удаление парсера
    сняло бы ссылку на документ у трети пар, а взамен потребовало бы вписать
    руками то, что и так вычисляется верно.
    🔴 Координата больше НЕ РЕШАЕТ, чей это лист, — она только подписывает,
    где о нём написано. Ошибка парсера теперь стоит неверной подписи,
    а не ложного родства на карточке: цена упала на порядок, и это и есть
    причина, по которой его можно держать.
    """
    people = {p["id"]: p for p in graph.get("people") or []}
    coord = by_coord(have)
    out = {pid: [] for pid in people}
    seen = {pid: set() for pid in people}

    def put(pid, stem, role, record, srcs, basis,
            as_written=None, hyp=None, disputed=None, kind=None):
        if pid not in out or stem in seen[pid]:
            return
        seen[pid].add(stem)
        out[pid].append({"file": have[stem], "stem": stem, "role": role,
                         "record": record, "srcs": sorted(srcs), "basis": basis,
                         "as_written": as_written, "hyp": hyp,
                         "disputed": disputed, "kind": kind})

    # какие источники разбирают какой лист — нужно и для подписи, и для перехода
    src_of = {}
    folio_of_src = {}
    for s in sources_doc.get("sources") or []:
        stems = source_folios(s, have, coord, project, folios)
        folio_of_src[s["id"]] = stems
        for stem in stems:
            src_of.setdefault(stem, set()).add(s["id"])

    # реестр — единственное основание
    for stem, folio in folios.items():
        if stem not in have or not folio_resolved(folio):
            continue
        for item in folio_people(folio):
            put(item["id"], stem, item["as"], item["record"],
                src_of.get(stem, set()) | set(folio.get("sources") or []),
                "folio", item["as_written"], item["hyp"],
                item["disputed"], folio_kind(folio))

    order = {r: i for i, r in enumerate(ROLE_ORDER)}
    for pid in out:
        out[pid].sort(key=lambda e: (order.get(e["role"], len(ROLE_ORDER)), e["stem"]))
    return {k: v for k, v in out.items() if v}


def debt(graph, sources_doc, folios, have, project=None):
    """Какие снимки ещё не доведены до карточек. Всё — вычисляется.

    Возвращает словарь:
      unregistered — снимок есть, записи в реестре нет;
      unresolved   — запись есть, `people` не заполнен;
      unreachable  — лист не попадает ни на одну карточку;
      wide_sources — источники, разбирающие больше одного листа.

    ⚙️ ДО 2026-08-11 ЭТА ФУНКЦИЯ ОТВЕЧАЛА НА ДРУГОЙ ВОПРОС — «что мешает
    выключить переходное основание `basis: source`». Основание выключено, а
    функция осталась и сменила смысл: теперь она мерит не готовность к правке
    кода, а остаток работы по реестру.
    ⚠️ `wide_sources` перестало быть ПРИЧИНОЙ долга и стало его приметой:
    источник-свод (д.504 ЦЕЛИКОМ и подобные) никогда никого не привязывал,
    но именно вокруг таких источников копятся неразобранные листы.
    🔴 `have` подавайте схлопнутым ПО СОДЕРЖИМОМУ (`web_scans`), а не сырым
    перечнем с диска: один разворот лежит под двумя именами — `d612_sk287.jpg`
    и `d612_sk287_yakim_birth.jpg`, байт в байт, — и `disk_scans` покажет их
    двумя. Проверено 2026-08-11: сырой перечень дал 192 снимка против 189
    и три ложных «нет записи в реестре».
    """
    att = attach(graph, sources_doc, folios, have, project)
    on_card = {e["stem"] for lst in att.values() for e in lst}
    coord = by_coord(have)
    wide = {}
    for s in sources_doc.get("sources") or []:
        stems = source_folios(s, have, coord, project, folios)
        if len(stems) > 1:
            wide[s["id"]] = stems
    return {
        "unregistered": sorted(set(have) - set(folios)),
        "unresolved": sorted(stem for stem in have
                             if not folio_resolved(folios.get(stem) or {})),
        # ⚠️ Лист, про который сказано «смотрели, наших нет», из долга ВЫХОДИТ:
        # он не потерян, он разобран. Иначе опись фонда висела бы в списке вечно.
        "unreachable": sorted(stem for stem in set(have) - on_card
                              if not folio_resolved(folios.get(stem) or {})),
        "wide_sources": wide,
    }
